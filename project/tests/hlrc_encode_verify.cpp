void require(bool condition, const char *message)
{
    if (!condition)
        throw std::runtime_error(message);
}

unsigned char certified_gf_mul(unsigned char a, unsigned char b)
{
    unsigned int product = 0;
    unsigned int x = a;
    while (b != 0) {
        if ((b & 1U) != 0)
            product ^= x;
        b >>= 1U;
        x <<= 1U;
        if ((x & 0x100U) != 0)
            x ^= 0x11dU;
    }
    return static_cast<unsigned char>(product);
}

const unsigned char *certified_parity(int k)
{
    switch (k) {
    case 64: return &CERTIFIED_PARITY_64[0][0];
    case 96: return &CERTIFIED_PARITY_96[0][0];
    case 128: return &CERTIFIED_PARITY_128[0][0];
    default: throw std::invalid_argument("unsupported certified HLRC k");
    }
}

void verify_matrix(int k, int r, int z)
{
    const int parity_count = r + z;
    std::vector<unsigned char> matrix(static_cast<size_t>(k + parity_count) * k);
    ECProject::gen_hlrc_matrix(matrix.data(), k, r, z);
    for (int row = 0; row < k; ++row)
        for (int col = 0; col < k; ++col)
            require(matrix[row * k + col] == (row == col ? 1 : 0), "systematic identity mismatch");
    const unsigned char *certified = certified_parity(k);
    for (int row = 0; row < parity_count; ++row)
        for (int col = 0; col < k; ++col)
            require(matrix[(k + row) * k + col] == certified[row * k + col],
                    "certified parity mismatch");
}

void verify_encoding(int k, int r, int z)
{
    constexpr int block_size = 257;
    const int parity_count = r + z;
    std::mt19937 random(0x484c5243U + k);
    std::uniform_int_distribution<int> bytes(0, 255);
    std::vector<std::vector<unsigned char>> data(k, std::vector<unsigned char>(block_size));
    std::vector<std::vector<unsigned char>> parity(parity_count, std::vector<unsigned char>(block_size));
    std::vector<unsigned char *> data_ptrs(k);
    std::vector<unsigned char *> parity_ptrs(parity_count);
    for (int i = 0; i < k; ++i) {
        std::generate(data[i].begin(), data[i].end(), [&] { return static_cast<unsigned char>(bytes(random)); });
        data_ptrs[i] = data[i].data();
    }
    for (int i = 0; i < parity_count; ++i)
        parity_ptrs[i] = parity[i].data();
    ECProject::encode_hlrc(k, r, z, data_ptrs.data(), parity_ptrs.data(), block_size);
    const unsigned char *certified = certified_parity(k);
    for (int row = 0; row < parity_count; ++row)
        for (int byte = 0; byte < block_size; ++byte) {
            unsigned char expected = 0;
            for (int col = 0; col < k; ++col)
                expected ^= certified_gf_mul(certified[row * k + col], data[col][byte]);
            require(parity[row][byte] == expected, "encoded byte mismatch");
        }
}

void verify_layout(int k, int r, int z, const std::vector<int> &expected_globals,
                   const std::vector<int> &expected_locals,
                   const std::vector<int> &logical_local_order)
{
    const int n = k + r + z;
    const auto groups = ECProject::get_hlrc_group_id_to_block_ids(k, r, z);
    const auto data_counts = ECProject::get_data_block_num_per_group(k, r, z, "HLRC");
    const auto global_counts = ECProject::get_global_parity_block_num_per_group(k, r, z, "HLRC");
    const auto local_counts = ECProject::get_local_parity_block_num_per_group(k, r, z, "HLRC");
    require(data_counts == std::vector<int>(k / 16, 16), "data counts mismatch");
    require(global_counts == expected_globals, "global counts mismatch");
    require(local_counts == expected_locals, "local counts mismatch");
    std::vector<int> seen(n);
    std::vector<int> physical_locals;
    for (int group = 0; group < k / 16; ++group) {
        int data = 0, global = 0, local = 0;
        for (int id : groups.at(group)) {
            require(id >= 0 && id < n, "block id out of range");
            ++seen[id];
            if (id < k) ++data;
            else if (id < k + r) ++global;
            else { ++local; physical_locals.push_back(id - (k + r)); }
        }
        require(data == data_counts[group] && global == global_counts[group] && local == local_counts[group],
                "group type count mismatch");
    }
    require(std::all_of(seen.begin(), seen.end(), [](int count) { return count == 1; }),
            "layout does not contain every block exactly once");
    require(logical_local_order.size() == physical_locals.size(), "local reorder size mismatch");
    for (int logical = 0; logical < z; ++logical)
        require(physical_locals.at(logical_local_order.at(logical)) == logical,
                "local logical output order mismatch");
}

void verify_invalid_parameters()
{
    const std::vector<std::vector<int>> invalid = {
        {63, 2, 6}, {64, 1, 6}, {64, 2, 10}, {95, 2, 8}, {96, 1, 8}, {96, 2, 6}, {96, 2, 10}, {97, 2, 8}, {128, 2, 6}, {128, 3, 10}, {129, 2, 10}
    };
    std::vector<unsigned char> matrix(140 * 128);
    for (const auto &parameters : invalid) {
        bool threw = false;
        try { ECProject::gen_hlrc_matrix(matrix.data(), parameters[0], parameters[1], parameters[2]); }
        catch (const std::invalid_argument &) { threw = true; }
        require(threw, "invalid HLRC parameters were accepted");
    }
}
